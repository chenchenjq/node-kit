import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { Readable } from "node:stream";
import { createOssKit, createAesGcmCredentialProtector } from "oss-kit/server";
import { previewObjectKey } from "oss-kit/rules";
import { memoryStore, mockOss } from "./mock-host.mjs";
const store = memoryStore(), oss = mockOss();
const security = createAesGcmCredentialProtector(randomBytes(32).toString("base64"));
const kit = createOssKit({ store, applicationPrefix: "packed-app", testPrefixes: ["isolated-tests"], authorize: async ctx => ctx === "allowed", credentials: security, ossTransportFactory: oss.factory });
const creds = { accessKeyId: "mock-key-id", accessKeySecret: "mock-long-secret-for-pack-test" };
const input = { name: "Packed Mock", region: "oss-cn-hangzhou", bucket: "mock-test-bucket", endpoint: "https://oss-cn-hangzhou-internal.aliyuncs.com" };
const config = await kit.createStorage("allowed", input, creds);
await kit.setDefaultStorage("allowed", config.id);
const strategy = await kit.saveStrategy("allowed", { code: "packed_attachments", name: "Mock only", description: "Needs host creation", prefix: "attachments", dateDirectory: "year-month-day", allowedExtensions: ["txt"], allowedMimeTypes: ["text/plain"] });
assert.equal((await kit.listStrategies("allowed"))[0].code, "packed_attachments");
assert.deepEqual(await kit.listStrategies("denied"), []);
const ref = await kit.upload("allowed", { strategyCode: strategy.code, originalName: "document.txt", mimeType: "text/plain", body: Readable.from([Buffer.from("packed "), Buffer.from("flow")]) });
const link = await kit.getAccessLink("allowed", ref);
assert.ok(link.expiresAt); assert.ok(link.url.includes("MOCK"));
const stream = await kit.read("allowed", ref), chunks = []; for await (const b of stream) chunks.push(b);
assert.equal(Buffer.concat(chunks).toString(), "packed flow");
await assert.rejects(kit.delete("denied", ref), { code: "FORBIDDEN" });
await kit.delete("allowed", ref); assert.equal(oss.objects.size, 0);
const result = await kit.testStorage("allowed", { input, credentials: creds, prefix: "isolated-tests" });
assert.equal(result.read.status, "passed"); assert.equal(result.cleanupRequired, false);
assert.equal(previewObjectKey({ applicationPrefix: "app", strategy, originalName: "a.txt", now: new Date("2026-09-15T00:00:00Z"), randomId: "rnd" }), "app/attachments/2026/09/15/rnd.txt");
// Actual SDK V4 signer, test keys only, no network or cloud authentication implied.
const signer = createOssKit({ store, applicationPrefix: "packed-app", authorize: async () => true, credentials: security });
const signed = new URL((await signer.getAccessLink("allowed", ref, { expiresInSeconds: 60 })).url);
assert.equal(signed.searchParams.get("x-oss-signature-version"), "OSS4-HMAC-SHA256");
assert.ok(!signed.hostname.includes("internal"));
assert.ok(!JSON.stringify(await kit.listStorage("allowed")).includes(creds.accessKeySecret));
console.log("Packed minimal flow PASS; OSS network is Mock; real cloud and anonymous access untested.");
