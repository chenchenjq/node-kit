import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { randomBytes } from "node:crypto";
import pg from "pg";
import { drizzle } from "drizzle-orm/node-postgres";
import { createOssKit, createAesGcmCredentialProtector } from "oss-kit/server";
import type { HostContext } from "../examples/next/lib/host.js";
import { createOssHost } from "../examples/next/lib/host.js";
import { createOssTables } from "../examples/next/lib/schema.js";
import { createDrizzleOssStore } from "../examples/next/lib/store.js";
import { createExampleFileRepository } from "../examples/next/lib/files.js";
import { mockOss } from "./mock-host.mjs";
const connection = JSON.parse(process.env.OSS_KIT_TEST_POSTGRES ?? "null");
if (!connection || connection.database !== "oss_kit_ephemeral_test") throw new Error("Only the isolated test database is allowed");
const pool = new pg.Pool({ ...connection, max: 12 }), db = drizzle(pool);
try {
  await pool.query(await readFile(new URL("../examples/next/migration.sql", import.meta.url), "utf8"));
  const tables = createOssTables(), security = createAesGcmCredentialProtector(randomBytes(32).toString("base64")), oss = mockOss();
  const make = (scope: string) => createOssKit<boolean>({ store: createDrizzleOssStore(db, tables, scope), applicationPrefix: scope, credentials: security, authorize: async ctx => ctx, ossTransportFactory: oss.factory });
  const a = make("scope-a"), b = make("scope-a"), other = make("scope-b");
  const input = { name: "Mock OSS real DB", region: "oss-cn-hangzhou", bucket: "mock-bucket" }, credentials = { accessKeyId: "mock-id", accessKeySecret: "mock-secret-for-test" };
  const c1 = await a.createStorage(true, input, credentials), c2 = await a.createStorage(true, input, credentials);
  await Promise.all(Array.from({ length: 60 }, (_, n) => (n % 2 ? a : b).setDefaultStorage(true, n % 3 ? c1.id : c2.id)));
  assert.equal((await a.listStorage(true)).filter(c => c.isDefault).length, 1);
  assert.deepEqual(await other.listStorage(true), []);
  const strategy = { code: "attachments", name: "需宿主创建", description: "Test fixture only", prefix: "files", allowedExtensions: ["txt"], allowedMimeTypes: ["text/plain"] };
  await a.saveStrategy(true, strategy);
  const ref = await a.upload(true, { strategyCode: "attachments", originalName: "old.txt", mimeType: "text/plain", body: Buffer.from("real-db mock-oss") });
  await a.setDefaultStorage(true, ref.storageConfigId === c1.id ? c2.id : c1.id);
  await a.saveStrategy(true, { ...strategy, prefix: "new", enabled: false });
  const stream = await a.read(true, ref), chunks = []; for await (const chunk of stream) chunks.push(chunk);
  assert.equal(Buffer.concat(chunks).toString(), "real-db mock-oss");
  const files = createExampleFileRepository(db, tables);
  const owner: HostContext = { userId: "owner", scope: "scope-a", admin: false, allowedStrategyCodes: ["attachments"] };
  const host = createOssHost({ db, tables, scope: "scope-a", applicationPrefix: "scope-a", credentials: security, files, testPrefixes: ["test-only"], authenticate: async () => owner, protectRequest: async () => {}, ossTransportFactory: oss.factory });
  const fileId = await files.save(owner.scope, owner.userId, ref), trusted = await files.get(owner.scope, fileId);
  assert.ok(trusted); assert.ok((await host.kit.getAccessLink(owner, trusted.reference)).expiresAt);
  await assert.rejects(host.kit.getAccessLink({ ...owner, userId: "attacker" }, ref), { code: "FORBIDDEN" });
  await assert.rejects(host.kit.getAccessLink(owner, { ...ref, originalName: "tampered.txt" }), { code: "FORBIDDEN" });
  await assert.rejects(host.kit.listStorage(owner), { code: "FORBIDDEN" });
  assert.deepEqual(await files.get("scope-b", fileId), null);
  const before = await a.listStorage(true);
  await assert.rejects(createDrizzleOssStore(db, tables, "scope-a").transaction(async v => { await v.saveStorage({ ...(await v.getStorage(c1.id))!, name: "rollback" }); throw new Error("abort"); }));
  assert.deepEqual(await a.listStorage(true), before);
  // The DB constraint protects against a writer violating the adapter contract too.
  await a.setDefaultStorage(true, c1.id);
  await assert.rejects(pool.query("UPDATE oss_kit_storage SET is_default = true WHERE scope = $1 AND id = $2", ["scope-a", c2.id]));
  await host.kit.delete(owner, trusted.reference); await files.remove(owner.scope, fileId);
  console.log("Real PostgreSQL PASS: concurrent defaults across clients, scope isolation, constraints, rollback, trusted file ownership and old references. OSS network Mock.");
} finally { await pool.end(); }
